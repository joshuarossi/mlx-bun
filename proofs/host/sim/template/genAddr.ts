// Write a driver's template constants (`Host.Ts.Sim.Addr`, host/sim/DecodeAddr.lean) as a Lean module from JSON.
// usage: bun proofs/host/sim/template/genAddr.ts <addr.json> [--out <file.lean>]
//   <addr.json>: {"module": "host.load.run.prompt.AddrFull", "namespace": "Host.Load.Run.Prompt", "name": "addrFull",
//   "doc": "…", "fwd", "emit", "cE", "cache", "gen", "tok", "nxt", "tvar", "kvar", "NL", "N0", "rope"} (the `Addr`
//   fields). The same file serves the generators' --addr (genFinal.ts, genExit.ts, gen.ts: module, name, fwd, emit,
//   cE, tok, nxt) and a template spec's `addr` (its places name the fields as "$fwd", …), so a template's places, its
//   halting facts and the composition read one set of addresses. Writes <proofs>/<module path>.lean unless --out.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const argv = process.argv.slice(2);
const oi = argv.indexOf("--out");
const out = oi >= 0 ? argv[oi + 1] : undefined;
if (oi >= 0) argv.splice(oi, 2);
const [path] = argv;
if (!path) throw new Error("usage: genAddr.ts <addr.json> [--out <file.lean>]");
const a = JSON.parse(readFileSync(path, "utf8"));
const fields = ["fwd", "emit", "cE", "cache", "gen", "tok", "nxt", "tvar", "kvar", "NL", "N0", "rope"] as const;
for (const f of [...fields, "module", "namespace", "name"]) if (a[f] === undefined) throw new Error(`${path}: no ${f}`);
for (const f of fields) if (!Number.isSafeInteger(a[f]) || a[f] < 0) throw new Error(`${path}: ${f} must be a natural number`);
if (a.fwd === a.emit) throw new Error(`${path}: fwd = emit`);
const file = out ?? join(import.meta.dir, "..", "..", "..", ...String(a.module).split(".")) + ".lean";
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, `import host.sim.DecodeAddr
namespace ${a.namespace}
open Host.Ts.Sim

/-! ${a.doc ?? `The driver's template constants \`${a.name}\``} (generated by \`host/sim/template/genAddr.ts\` from \`${path.split("/").pop()}\`). -/

def ${a.name} : Addr :=
  { ${fields.map(f => `${f} := ${a[f]}`).join(", ")}, fwd_emit := by decide }

end ${a.namespace}
`);
console.log(`${a.namespace}.${a.name}: ${file}`);
